HERE = Path(__file__).parent
ORIGIN = (81.62, 14.62)
SOURCE_DATE = "2026-11-20"
REFERENCE = "FICTIONAL SAMPLE generated by app/sources/samples/generate.py. Not government data."
M_PER_DEG_LAT = 111_320.0


def to_lonlat(east: float, north: float) -> tuple[float, float]:
    lon0, lat0 = ORIGIN
    lon = lon0 + east / (M_PER_DEG_LAT * math.cos(math.radians(lat0)))
    return round(lon, 7), round(lat0 + north / M_PER_DEG_LAT, 7)


def geo(poly_m: Polygon) -> dict:
    return mapping(Polygon([to_lonlat(x, y) for x, y in poly_m.exterior.coords]))


def blob(east: float, north: float, r: float, seed: int, n: int = 48) -> Polygon:
    """A lake-like outline in metres: a circle with a few smooth lobes."""
    a, b = seed * 0.7, seed * 1.3
    pts = []
    for i in range(n):
        t = 2 * math.pi * i / n
        rr = r * (1 + 0.12 * math.sin(3 * t + a) + 0.07 * math.cos(5 * t + b))
        pts.append((east + rr * math.cos(t), north + rr * 0.8 * math.sin(t)))
    return Polygon(pts)


def feature(poly_m: Polygon, **props) -> dict:
    return {"type": "Feature", "properties": props, "geometry": geo(poly_m)}


def collection(features: list[dict]) -> str:
    return json.dumps({"type": "FeatureCollection", "features": features}, ensure_ascii=False, indent=1) + "\n"


def csv_text(rows: list[dict], fields: list[str]) -> str:
    out = io.StringIO()
    w = csv.DictWriter(out, fieldnames=fields, lineterminator="\n")
    w.writeheader()
    for row in rows:
        w.writerow(row)
    return out.getvalue()


def write(folder: str, files: dict[str, str]) -> None:
    d = HERE / folder
    d.mkdir(exist_ok=True)
    files = {"manifest.yml": f"source_date: {SOURCE_DATE}\nreference: \"{REFERENCE}\"\n", **files}
    for name, content in files.items():
        (d / name).write_text(content, encoding="utf-8", newline="\n")


