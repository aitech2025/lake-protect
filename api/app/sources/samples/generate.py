"""Write the fictional sample files for the four template connectors.

    python -m app.sources.samples.generate

Every place, ID, reference and name here is invented. The files sit in open sea about 15 km
north-east of the demo world (DECISIONS.md D-015), so nothing can coincide with a real lake,
parcel or person. Each file follows its connector's data contract and includes the awkward cases
the engine must handle: a notified lake with no reference, a lake with no outline, a weaker
outline, two sources that disagree, an outline too inaccurate to load, a status upgrade, owner
names that must be removed, and an extent that does not match its drawing.
"""
