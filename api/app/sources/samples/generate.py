def lake_polygons() -> dict[str, Polygon]:
    return {k: blob(*v["at"], v["r"], v["seed"]) for k, v in LAKES.items() if v["at"]}


def hmda_lpc() -> None:
    polys = lake_polygons()
    rows = []
    for lake_id, v in LAKES.items():
        area_ha = round(polys[lake_id].area / 10_000, 2) if lake_id in polys else ""
        rows.append({
            "lake_id": lake_id, "lake_name": v["name"], "lake_name_te": v["te"], "district": "Sample District",
            "mandal": "Sample Mandal", "village": v["village"], "survey_numbers": v["survey"], "area_ha": area_ha,
            "notification_status": v["status"], "notification_ref": v["ref"], "notification_date": v["date"],
            "notification_url": "", "certified_by": "Sample office (fictional)" if v["ref"] else "",
            "positional_accuracy_m": "",
        })
    fields = ["lake_id", "lake_name", "lake_name_te", "district", "mandal", "village", "survey_numbers", "area_ha",
              "notification_status", "notification_ref", "notification_date", "notification_url", "certified_by",
              "positional_accuracy_m"]
    ftl = [feature(p, lake_id=k, method="total_station", positional_accuracy_m=3.5) for k, p in polys.items()]
    write("hmda_lpc", {"lakes.csv": csv_text(rows, fields), "ftl.geojson": collection(ftl)})


