def bhu_bharati() -> None:
    polys = lake_polygons()
    del polys["S-004"]  # not a lake in the land records
    cores = unary_union([affinity.scale(p, 0.7, 0.7) for p in polys.values()])
    ftls = unary_union(list(polys.values()))
    features, rows = [], []
    seq = {"Sample Village 1": 0, "Sample Village 2": 0}
    cell = 250
    index = 0
    for north in range(1250 - cell, -1750 - 1, -cell):
        for east in range(-1750, 2000, cell):
            sq = box(east, north, east + cell, north + cell)
            village = "Sample Village 1" if east < 750 else "Sample Village 2"
            seq[village] += 1
            survey_no = str(seq[village])
            core_share = sq.intersection(cores).area / sq.area
            ftl_share = sq.intersection(ftls).area / sq.area
            if core_share > 0.2:
                recorded = "Kunta"
            elif ftl_share > 0.15:
                recorded = "Shikam" if index % 2 == 0 else "Patta"
            else:
                recorded = {0: "Sarkari", 1: "Sarkari", 2: "Assigned", 3: "Inam"}.get(index % 10, "Patta")
            if index == 17:
                recorded = "Lavani patta"
            elif index == 58:
                recorded = "Devadaya"
            elif index == 101:
                recorded = "Gairan"  # not in the mapping: loads as unknown, with a warning
            extent = sq.area / 4046.8564224
            if index in (44, 130):
                extent *= 1.25  # recorded extent does not match the drawing: a warning
            private = recorded in ("Patta", "Lavani patta", "Assigned", "Inam")
            features.append(feature(sq, district="Sample District", mandal="Sample Mandal", village=village,
                                    survey_no=survey_no, sub_division="", positional_accuracy_m=6.0))
            rows.append({
                "district": "Sample District", "mandal": "Sample Mandal", "village": village, "survey_no": survey_no,
                "sub_division": "", "bhudhaar": f"S{index + 1:013d}", "land_classification": recorded,
                "extent_acres": f"{extent:.4f}",
                # Personal fields as a real extract might carry them. The engine removes both columns.
                "pattadar_name": f"FICTIONAL-NAME-{index + 1:03d}" if private else "",
                "pattadar_mobile": "0000000000" if private else "",
            })
            index += 1
    rows.append({"district": "Sample District", "mandal": "Sample Mandal", "village": "Sample Village 2", "survey_no": "999",
                 "sub_division": "", "bhudhaar": "S9999999999999", "land_classification": "Sarkari", "extent_acres": "2.0000",
                 "pattadar_name": "", "pattadar_mobile": ""})  # no polygon: refused
    fields = ["district", "mandal", "village", "survey_no", "sub_division", "bhudhaar", "land_classification",
              "extent_acres", "pattadar_name", "pattadar_mobile"]
    write("bhu_bharati", {"village_parcels.geojson": collection(features), "ror_extract.csv": csv_text(rows, fields)})


